"""
script_builder.py
Validation script builder: embeds the LLM-generated predicate into the CodeQL
template for its role.
"""
import re
from typing import Optional, Tuple

from global_data_model.analysis_result import SpecificationUnion
from codeql_agent.role_registry import RoleConfig
from logger import StdoutLogger


STDOUT_LOG_PHASE = "codeql_agent/script_builder"

# Predicate declaration head "predicate <name>(" -- normalization here and the
# assembly-time check in assembler share the same regex, so the two cannot
# drift and surface as an unrelated compile error.
PREDICATE_HEAD_RE = re.compile(r"(predicate\s+)(\w+)(\s*\()")


def replace_predicate_name(code: str, expected_name: str) -> Tuple[str, Optional[str]]:
    """
    Force-rename the first `predicate <name>(` in the code to expected_name.

    Returns:
        (new_code, old_name); old_name is None when no rename happened (no
        predicate declaration head, or the name already matches).
    """
    m = PREDICATE_HEAD_RE.search(code)
    if m is None or m.group(2) == expected_name:
        return code, None
    new_code = PREDICATE_HEAD_RE.sub(
        lambda mm: f"{mm.group(1)}{expected_name}{mm.group(3)}", code, count=1,
    )
    return new_code, m.group(2)


class ScriptBuilder:
    """Wrap predicate code into a complete, runnable CodeQL query script for a role."""

    def build(
        self,
        spec: SpecificationUnion,
        config: RoleConfig,
        predicate_name: str,
        predicate_code: str,
    ) -> str:
        """
        Args:
            spec:            current specification
            config:          role configuration (includes the template)
            predicate_name: predicate name, e.g. "is_source_a1b2c3d4"
            predicate_code:  full predicate code generated by the LLM
        Returns:
            Complete CodeQL query script string.
        """
        # Make the predicate name match the template reference (the LLM may
        # choose its own name; renaming is idempotent)
        predicate_code = self.normalize_predicate_name(
            predicate_code, predicate_name, config
        )

        # Fill the template
        ql_script = config.fetch_template.format(
            predicate_implication=predicate_code,
            predicate_name=predicate_name,
        )

        return ql_script

    @staticmethod
    def predicate_line_offset(config: RoleConfig) -> int:
        """
        Line offset of the predicate code inside the wrapped script.

        CodeQL reports line numbers relative to the wrapped script, but the model
        never sees the wrapper, so subtract this offset to map errors back to the
        model's own code (predicate line 1 = offset + 1).
        """
        return config.fetch_template.split("{predicate_implication}")[0].count("\n")

    @staticmethod
    def normalize_predicate_name(
        code: str,
        expected_name: str,
        config: Optional[RoleConfig] = None,   # kept for call-site compatibility; unused
    ) -> str:
        """
        Ensure the LLM-generated predicate name matches the expected name.
        Other names (isSource, is_source, is_summary_01, ...) are replaced.

        **The execution and persistence paths share this entry point**: build()
        calls it when wrapping the script, and agent.py calls it when extracting
        code. This keeps SpecResult.predicate_code and the persisted
        codeql_agent_spec_scripts.json in agreement with the assembler reference
        `is_<spec_id>`. Renaming only the execution script would leave the
        persisted name different and make Phase 4 fail with
        "could not resolve predicate".

        Log a warning on a real rename; silent renaming previously hid the
        mismatch.
        """
        new_code, renamed_from = replace_predicate_name(code, expected_name)
        if renamed_from is not None:
            StdoutLogger.warning(
                f"Predicate name normalized: LLM produced `{renamed_from}` -> expected "
                f"`{expected_name}`; if only the execution script were renamed, Phase 4 "
                f"would report could not resolve predicate",
                STDOUT_LOG_PHASE,
            )
        return new_code

    # Backward compatibility: older internal call sites use the private name
    _normalize_predicate_name = normalize_predicate_name